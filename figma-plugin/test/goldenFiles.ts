import { formatUnit, hapticCodeParts, patternCode } from "../src/core/codegen";
import { toTimeline, type HapticEvent, type PatternSpec, type Trigger } from "../src/core/model";
import { PRESETS } from "../src/core/presets";
import { buzz, tap } from "../src/core/testing";

// Kotlin files that Gradle compiles in jindong-core and jindong-compose tests (see the
// commonTest srcDirs in their build.gradle.kts). Each pattern file is the generator's output,
// and FigmaGoldenCases.kt restates the same card as a literal timeline for comparison.

const HEADER = "// GENERATED by figma-plugin `yarn golden` from the plugin's code generator. Do not edit.";
const PACKAGE = "package io.github.compose.jindong.figma.golden";
const INDENT = "    ";

function edgeCase(name: string, events: HapticEvent[], trailingMs: number): PatternSpec {
  return { schema: 1, name, description: "", tone: "neutral", events, trailingMs };
}

export const GOLDEN_EDGE_CASES: PatternSpec[] = [
  edgeCase("Leading Silence", [buzz(120, 40)], 0),
  edgeCase("Tap Then Buzz", [tap(0, 0.75, 0.9), buzz(0, 80, 0.25, 0.2)], 40),
  edgeCase("Silent Buzz", [buzz(0, 30, 0)], 10),
  edgeCase("Sharp Buzz", [buzz(0, 70, 0.5, 0.8)], 0),
  edgeCase("Named Intensities", [buzz(0, 20, 0.25), buzz(10, 20, 0.5), buzz(10, 20, 0.75), buzz(10, 20, 1)], 0),
  edgeCase("성공 진동", [tap(0, 0.6)], 0),
  edgeCase("3 Taps!", [tap(0, 1), tap(100, 1), tap(100, 1)], 0),
  // Changing these letters' case would add combining marks, which Kotlin names reject.
  edgeCase("İptal", [tap(0, 0.8)], 0),
  edgeCase("ǰet", [buzz(0, 30)], 0),
];

/** Path under figma-plugin/golden → file content. */
export function goldenFiles(): Map<string, string> {
  const cases = [...PRESETS, ...GOLDEN_EDGE_CASES];
  const files = new Map<string, string>();
  cases.forEach((c, i) => {
    files.set(`core/Golden${String(i + 1).padStart(2, "0")}.kt`, `${HEADER}\n${PACKAGE}\n\n${patternCode(c)}\n`);
  });
  files.set("core/FigmaGoldenCases.kt", casesFile(cases));
  files.set("core/FigmaCodegenGoldenTest.kt", TEST_FILE);
  files.set("compose/FigmaTriggerGolden.kt", triggerFile());
  return files;
}

function casesFile(cases: PatternSpec[]): string {
  const entries = cases.map((c) => {
    const timeline = toTimeline(c);
    const events = timeline.events.map(
      (e) =>
        `${INDENT.repeat(4)}ScheduledHapticEvent(startTimeMs = ${e.startMs}L, durationMs = ${e.durationMs}L, ` +
        `intensity = HapticIntensity.Custom(${formatUnit(e.intensity)}), ` +
        `eventType = HapticEventType.${e.type === "transient" ? "TRANSIENT" : "CONTINUOUS"}, ` +
        `sharpness = ${formatUnit(e.sharpness)}),`,
    );
    return [
      `${INDENT}FigmaGoldenCase(`,
      `${INDENT.repeat(2)}name = ${kotlinString(c.name)},`,
      `${INDENT.repeat(2)}generated = ${generatedName(c)},`,
      `${INDENT.repeat(2)}expected = HapticPattern(`,
      `${INDENT.repeat(3)}listOf(`,
      ...events,
      `${INDENT.repeat(3)}),`,
      `${INDENT.repeat(3)}durationMs = ${timeline.durationMs}L,`,
      `${INDENT.repeat(2)}),`,
      `${INDENT}),`,
    ].join("\n");
  });
  return [
    HEADER,
    PACKAGE,
    "",
    "import io.github.compose.jindong.core.model.HapticEventType",
    "import io.github.compose.jindong.core.model.HapticIntensity",
    "import io.github.compose.jindong.core.model.HapticPattern",
    "import io.github.compose.jindong.core.model.ScheduledHapticEvent",
    "",
    "internal class FigmaGoldenCase(val name: String, val generated: HapticPattern, val expected: HapticPattern)",
    "",
    "internal val figmaGoldenCases: List<FigmaGoldenCase> = listOf(",
    ...entries,
    ")",
    "",
  ].join("\n");
}

// The generated `val` name, read back from the generator's own output so this file follows it.
function generatedName(c: PatternSpec): string {
  const match = patternCode(c).match(/^val (\S+): HapticPattern/m);
  if (!match) throw new Error(`No val in generated code for ${c.name}`);
  return match[1];
}

const TEST_FILE = `${HEADER}
${PACKAGE}

import io.github.compose.jindong.core.model.HapticPattern
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.shouldBe

class FigmaCodegenGoldenTest :
    FunSpec({
        figmaGoldenCases.forEach { case ->
            test("plugin code for \${case.name} plays the card's timeline") {
                case.generated.timelineValues() shouldBe case.expected.timelineValues()
            }
        }
    })

// Compares values, not objects: HapticIntensity.Custom(0.25f) is not equal to HapticIntensity.LIGHT.
private fun HapticPattern.timelineValues(): Pair<List<List<Any>>, Long> =
    events.map { listOf(it.startTimeMs, it.durationMs, it.eventType, it.intensity.value, it.sharpness) } to durationMs
`;

const TRIGGER_FUNCTIONS: [string, string, Trigger][] = [
  ["TapTriggerGolden", "", "tap"],
  ["EnterTriggerGolden", "", "enter"],
  ["StateTriggerGolden", "state: Any?", "state"],
];

function triggerFile(): string {
  const parts = TRIGGER_FUNCTIONS.map(([, , trigger]) => hapticCodeParts("TriggerGoldenHaptic", trigger));
  const imports = new Set([
    "androidx.compose.runtime.Composable",
    "io.github.compose.jindong.core.dsl.buildHapticPattern",
    "io.github.compose.jindong.core.model.HapticPattern",
    ...parts.flatMap((p) => p.imports),
  ]);
  const functions = TRIGGER_FUNCTIONS.map(([name, params], i) =>
    [
      "@Composable",
      `internal fun ${name}(${params}) {`,
      ...parts[i].body.split("\n").map((line) => INDENT + line),
      "}",
    ].join("\n"),
  );
  // Two default-named "Button" instances with different haptics in one composable: the snippets must not collide.
  functions.push(
    [
      "@Composable",
      "internal fun TwoTapTriggersGolden() {",
      ...hapticCodeParts("TriggerGoldenHaptic", "tap", "Button").body.split("\n").map((line) => INDENT + line),
      ...hapticCodeParts("SecondGoldenHaptic", "tap", "Button").body.split("\n").map((line) => INDENT + line),
      "}",
    ].join("\n"),
  );
  // Two buttons linked to the same haptic, each pasted with its layer name.
  functions.push(
    [
      "@Composable",
      "internal fun SharedHapticTriggersGolden() {",
      ...hapticCodeParts("TriggerGoldenHaptic", "tap", "Pay button").body.split("\n").map((line) => INDENT + line),
      ...hapticCodeParts("TriggerGoldenHaptic", "tap", "Confirm button").body.split("\n").map((line) => INDENT + line),
      "}",
    ].join("\n"),
  );
  return [
    HEADER,
    PACKAGE,
    "",
    ...[...imports].sort().map((name) => `import ${name}`),
    "",
    "private val TriggerGoldenHaptic: HapticPattern = buildHapticPattern { transient() }",
    "private val SecondGoldenHaptic: HapticPattern = buildHapticPattern { transient() }",
    "",
    functions.join("\n\n"),
    "",
  ].join("\n");
}

function kotlinString(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;
}
